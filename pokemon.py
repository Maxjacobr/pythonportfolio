def train():
    global level
    print(f"\n {name} did ten pushups.")
    level = level + 1
    print("Training complete.")
    print("Current level:", level)


def rest():
    print("\nYour Pokémon is resting.")
    print("----- Pokémon Info -----")
    print("Name :", name)
    print("Level:", level)
    print("------------------------")


def gym_battle():
    global level
    print("\nYou enter a gym battle.")
    outcome = random.randint(1, 2)

    if outcome == 1:
        print("Your Pokémon won the battle.")
        level = level + 2
        print("Level increased to:", level)
    else:
        print("Your Pokémon lost the battle.")
        print("Level stays the same.")

